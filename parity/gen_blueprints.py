# Generates parity/suites/items_blueprints*/parity_main.nss from a list of base-game item blueprints.
# The list comes from: openwinter-tools list "" uti --base > uti_base.txt
import sys, os

src = sys.argv[1]
names = sorted(set(open(src).read().split()))
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "suites")
parts = int(sys.argv[2]) if len(sys.argv) > 2 else 2
per = (len(names) + parts - 1) // parts
chunk = 60

for part in range(parts):
    group = names[part * per:(part + 1) * per]
    suite = "items_blueprints" + str(part + 1)
    os.makedirs(os.path.join(root, suite), exist_ok=True)
    out = []
    out.append("// Every base-game item blueprint (part %d of %d): value, weight, AC, stacks, charges and properties.\n" % (part + 1, parts))
    out.append("// Generated by parity/gen_blueprints.py.\n")
    out.append('#include "parity_items"\n\n')
    out.append("""void B(string sResRef)
{
    object o = CreateObject(OBJECT_TYPE_ITEM, sResRef, PCentre());
    string k = "bp." + sResRef + ".";
    PItemCore(k, o);
    if (!GetIsObjectValid(o)) return;
    PLog(k + "props", PIpList(o));
    if (!GetIdentified(o))
    {
        SetIdentified(o, TRUE);
        PLogI(k + "gpv.identified", GetGoldPieceValue(o));
        SetIdentified(o, FALSE);
    }
    int nStack = StringToInt(Get2DAString("baseitems", "Stacking", GetBaseItemType(o)));
    if (nStack > 1)
    {
        SetItemStackSize(o, 3);
        PLogI(k + "stack3", GetItemStackSize(o));
        PLogI(k + "gpv3", GetGoldPieceValue(o));
        PLogI(k + "weight3", GetWeight(o));
        SetItemStackSize(o, 10000);
        PLogI(k + "stackmax", GetItemStackSize(o));
    }
    DestroyObject(o);
}

""")
    chunks = [group[i:i + chunk] for i in range(0, len(group), chunk)]
    for i, c in enumerate(chunks):
        out.append("void C%d()\n{\n" % i)
        for n in c:
            out.append('    B("%s");\n' % n)
        if i == len(chunks) - 1:
            out.append("    PDone();\n")
        out.append("}\n\n")
    out.append("void main()\n{\n")
    for i in range(len(chunks)):
        out.append("    DelayCommand(%.1f, C%d());\n" % (2.0 + 0.2 * i, i))
    out.append("}\n")
    with open(os.path.join(root, suite, "parity_main.nss"), "w", newline="") as f:
        f.write("".join(out))
    print(suite, len(group))
