"""Generate isolated self-buff application cases from installed spell metadata.
Run from repository root: python parity/gen_buffscope.py
The curated IDs have legal self targets. Cheat casts isolate application from slot availability; they do not prove all
levels, metamagic legality, saving throws or multiplayer targeting.
"""
import csv,io,json,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
IDS=[1,3,6,9,13,20,21,22,38,42,47,49,50,62,65,73,74,78,84,88,90,92,95,99,100,102,103,104,105,106,113,117,119,120,121,125,133,134,136,137,138,139,140,141,150,151,154,157,160,162,163,168,169,172,186,187,189,354,355,356,357,358,359,360,361,362,365,369,372,373,374,376,414,415,417,418,420,421,422,429,438,441,442,443,444,450,455,456,458,519,522,524,525]
# An empty diagnostic user root prevents personal overrides from changing the stock catalog.
# Build OpenWinter.Tools in Release before running this generator.
work=ROOT/'out'/'buffscope-source'
(work/'config').mkdir(parents=True,exist_ok=True)
with (ROOT/'config'/'local.json').open(encoding='utf-8-sig') as f: cfg=json.load(f)
cfg['userRoot']=str(work/'user')
cfg['module']=str(Path(cfg['gameRoot'])/'data'/'nwm'/'Prelude.nwm')
cfg['liveUserData']=False
with (work/'config'/'local.json').open('w',encoding='utf-8',newline='') as f: json.dump(cfg,f)
tool=ROOT/'src'/'OpenWinter.Tools'/'bin'/'Release'/'net10.0'/'openwinter-tools.dll'
text=subprocess.check_output(['dotnet',str(tool),'2da','spells','2000','--base'],cwd=work,text=True,encoding='utf-8')
text=text[text.index('row\t'):]
rows={int(r['row']):r for r in csv.DictReader(io.StringIO(text),delimiter='\t')}
for batch in range((len(IDS)+11)//12):
 folder=ROOT/'parity'/'suites'/f'buffscope{batch+1:02}'
 folder.mkdir(exist_ok=True)
 lines=['// Generated by parity/gen_buffscope.py; metadata read from installed spells.2da.','#include "parity_buffscope"','void main() {']
 for cell,spell in enumerate(IDS[batch*12:batch*12+12]):
  row=rows[spell]
  assert int(row['TargetType'],0)&1, f'{spell}: no self-target flag'
  assert row['ImpactScript']!='****', f'{spell}: no authored impact script'
  blueprint='nw_drowmage010' if row['Wiz_Sorc']!='****' else 'nw_drowcler010' if row['Cleric']!='****' else 'nw_hen_sha_11' if row['Bard']!='****' else 'nw_drowmage010'
  if spell==163: blueprint='nw_bandit001' # no innate SR: isolate the Silence self-target rule from a random resistance check
  lines.append(f' BCase({cell},{spell},"{blueprint}"); // {row["Label"]}')
 lines+=[' DelayCommand(6.0,PDone());','}']
 with (folder/'parity_main.nss').open('w',encoding='utf-8',newline='') as f:f.write('\n'.join(lines)+'\n')
 with (folder/'suite.json').open('w',encoding='utf-8',newline='') as f:json.dump({'seconds':12,'size':12,'tile':4},f);f.write('\n')
print(f'{len(IDS)} spell application cases in {batch+1} suites')
