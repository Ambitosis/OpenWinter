"""Writes the visual scene parity/visual/scenes/encounterrules (scene.json, creature fixtures, er_plan.nss).

Groups of six identical encounters lie on top of each other, each with its own creature copy (tag ES_1..ES_6)
and spawn point, so one walk-in by the player gives six samples of how many creatures a configuration spawns.
Then single encounters probe who triggers them, spawn options, resets, factions and spawn spots.
"""
import json, math, os

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "visual", "scenes", "encounterrules")
os.makedirs(HERE, exist_ok=True)

# label, part, fields, list CR
GROUPS = [
    ("n1", "A", {"DifficultyIndex": 2}, 1), ("n025", "A", {"DifficultyIndex": 2}, 0.25), ("n05", "A", {"DifficultyIndex": 2}, 0.5),
    ("n01", "A", {"DifficultyIndex": 2}, 0.1), ("h1", "A", {"DifficultyIndex": 3}, 1), ("h025", "A", {"DifficultyIndex": 3}, 0.25),
    ("i1", "A", {"DifficultyIndex": 4, "MaxCreatures": 30}, 1), ("i3", "A", {"DifficultyIndex": 4}, 3),
    ("e025", "A", {"DifficultyIndex": 1}, 0.25), ("v025", "A", {"DifficultyIndex": 0}, 0.25), ("n2", "A", {"DifficultyIndex": 2}, 2),
    ("b025", "B", {"DifficultyIndex": 2}, 0.25),   # with a level 1 henchman beside the player
    ("c1", "C", {"DifficultyIndex": 2}, 1),        # with a level 10 henchman beside the player
    ("l5n1", "D", {"DifficultyIndex": 2}, 1), ("l5n025", "D", {"DifficultyIndex": 2}, 0.25), ("l5h1", "D", {"DifficultyIndex": 3}, 1),
    ("l5i3", "D", {"DifficultyIndex": 4}, 3),
    ("l10n1", "E", {"DifficultyIndex": 2, "MaxCreatures": 30}, 1), ("l10n3", "E", {"DifficultyIndex": 2}, 3),
]
# label, fields, extra placement
SINGLES = [
    ("hen0", {"PlayerOnly": 0}, {}),            # the henchman walks in alone
    ("npc0", {"PlayerOnly": 0}, {}),            # a hostile-to-the-encounter commoner walks in
    ("so1", {"SpawnOption": 1, "Respawns": -1, "Reset": 1, "ResetTime": 1}, {}),
    ("so0", {"SpawnOption": 0, "Respawns": -1, "Reset": 1, "ResetTime": 1}, {}),
    ("so1n", {"SpawnOption": 1, "Respawns": 2, "Reset": 1, "ResetTime": 1}, {}),
    ("so1t", {"SpawnOption": 1, "Respawns": -1, "Reset": 1, "ResetTime": 30}, {}),
    ("so1r0", {"SpawnOption": 1, "Respawns": -1, "Reset": 0}, {}),
    ("alive", {"SpawnOption": 1, "Respawns": -1, "Reset": 1, "ResetTime": 1}, {}),
    ("fac2", {"Faction": 2}, {}),
    ("nosp2", {}, {"ox": 6, "oy": 6, "w": 4, "h": 4, "spawnPoints": []}),
    ("face", {}, {"spawnPoints": "face"}),
]
BASE = {"PlayerOnly": 1, "Faction": 1, "MaxCreatures": 20, "RecCreatures": 1, "SpawnOption": 1, "Reset": 0, "Respawns": 0,
        "DifficultyIndex": 2, "Active": 1, "OnEntered": "er_enter", "OnExit": "er_exit", "OnExhausted": "er_exh", "OnHeartbeat": ""}

cols, step = 8, 18
encs, spots = [], []
def spot(i):
    return 12 + (i % cols) * step, 12 + (i // cols) * step
i = 0
for label, part, fields, cr in GROUPS:
    x, y = spot(i); i += 1
    spots.append((label, x, y))
    for k in range(1, 7):
        a = math.radians(30 + 60 * (k - 1))
        s = dict(BASE); s.update(fields)
        encs.append({"from": "nw_goblingrp", "tag": f"ER_{label.upper()}_{k}", "x": x, "y": y, "w": 6, "h": 6, "set": s,
                     "creatures": [{"resref": f"er_{k}", "cr": cr}], "spawnPoints": [[round(x + 7 * math.cos(a), 2), round(y + 7 * math.sin(a), 2), 90]]})
for label, fields, extra in SINGLES:
    x, y = spot(i); i += 1
    spots.append((label, x, y))
    s = dict(BASE); s.update(fields)
    e = {"from": "nw_goblingrp", "tag": f"ER_{label.upper()}", "x": x, "y": y, "w": 6, "h": 6, "set": s,
         "creatures": [{"resref": "er_1", "cr": 1}], "spawnPoints": [[x + 5, y + 5, 90]]}
    for key, v in extra.items():
        e[key] = v
    if extra.get("spawnPoints") == "face":
        e["spawnPoints"] = [[x + 5, y + 5, 45], [x - 5, y + 5, 200]]
    encs.append(e)

scene = {"tileset": "tde01", "tile": 4, "size": 16, "pc": [4, 4, 0], "facing": 90, "seconds": 420, "gui": True, "chatLog": True,
         "factions": "Prelude", "encounters": encs}
with open(os.path.join(HERE, "scene.json"), "w", encoding="utf-8", newline="") as f:
    json.dump(scene, f, indent=1)
for k in range(1, 7):
    with open(os.path.join(HERE, f"er_{k}.utc.json"), "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps({"template": "nw_goblina", "hitPoints": 1, "tag": f"ES_{k}", "scripts": {"ScriptSpawn": "er_spawn"}}) + "\n")
for name, level in (("er_h1", 1), ("er_h10", 10)):
    with open(os.path.join(HERE, name + ".utc.json"), "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps({"template": "nw_bandit001", "hitPoints": 200, "classLevels": [{"class": 4, "level": level}]}) + "\n")
# Where each test's encounter(s) lie, for the scene script.
with open(os.path.join(HERE, "er_plan.nss"), "w", encoding="utf-8", newline="") as f:
    f.write("// Generated by parity/gen_encounterrules.py: where each test's encounters lie.\n")
    f.write("vector ErSpot(string sLabel)\n{\n")
    for label, x, y in spots:
        f.write(f'    if (sLabel == "{label}") return Vector({x}.0, {y}.0, 0.0);\n')
    f.write("    return Vector(0.0, 0.0, 0.0);\n}\n")
print(len(encs), "encounters,", len(spots), "spots")
