"""Writes the visual scene parity/visual/scenes/encounterwaves: how far from the creature that sets an encounter off a
party member still counts, and the respawn waves' budget (the point pool, the points in play and the
remembered last-entered creature). docs/ENCOUNTERS.md has what was learned.

Range trials ("r*"): a single-shot encounter (one CR 1 entry, blueprint CR 1, MaxCreatures 50, Normal) and the level 1
player walking in from the south; a level 12 henchman (or a plain level 12 NPC) stands still at an offset from the
point where she enters. Alone she gets the minimum, 1; a counted henchman makes it 42.

Wave trials ("w*"): continuous encounters (Reset, ResetTime 4 s, Respawns -1, Impossible) with the player standing
inside; each wave is counted and killed (EffectDeath), and the respawns are counted the same way.
"""
import json, math, os

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "visual", "scenes", "encounterwaves")
os.makedirs(HERE, exist_ok=True)

BASE = {"PlayerOnly": 1, "Faction": 1, "MaxCreatures": 50, "RecCreatures": 1, "SpawnOption": 1, "Reset": 0, "Respawns": 0,
        "DifficultyIndex": 2, "Active": 1, "OnEntered": "ew_enter", "OnExit": "", "OnExhausted": "ew_exh", "OnHeartbeat": ""}

# label, who (h12 = level 12 henchman, n12 = plain level 12 NPC, "" = nobody), dx, dy from the entry point.
RANGE = [("r0", "", 0, 0), ("r29x", "h12", 29, 0), ("r31x", "h12", 31, 0), ("r29y", "h12", 0, 29), ("r31y", "h12", 0, 31),
         ("r25d", "h12", 25, 25), ("r29d", "h12", 29, 29), ("r31d", "h12", 29, 31), ("rnpc", "n12", 5, 0),
         ("r35x", "h12", 35, 0), ("rm29x", "h12", -29, 0), ("rm31x", "h12", -31, 0)]
RSPOTS = [(x, y) for y in (25, 75, 125) for x in (25, 75, 125, 175)]
# label, list CR, blueprint (ew_c1: CR 1; ew_c6: CR 6; ew_g: the stock goblin), RecCreatures, MaxCreatures, plan.
WAVES = [("w1", 3.0, "ew_c1", 3, 50, "stay"),      # list CR above the creature's: points stay in play
         ("w1b", 1.0, "ew_c1", 3, 50, "stay"),     # matched: full respawns
         ("w1c", 1.0, "ew_g", 1, 50, "stay"),      # the stock goblin under a CR 1 entry (the old 12 -> 3 reading)
         ("w2", 1.0, "ew_c1", 3, 50, "npc"),       # a creature walks through after her and is destroyed
         ("w3", 6.0, "ew_c6", 1, 50, "stay"),      # one CR 6 creature leaves points over for the respawn
         ("w4", 1.0, "ew_c1", 1, 4, "stay")]       # MaxCreatures 4 leaves points over
WSPOTS = [(x, 175) for x in (25, 65, 105, 145, 185, 225)]

encs, steps = [], []
for (label, who, dx, dy), (x, y) in zip(RANGE, RSPOTS):
    encs.append({"from": "nw_goblingrp", "tag": f"EW_{label.upper()}", "x": x, "y": y, "w": 6, "h": 6, "set": dict(BASE),
                 "creatures": [{"resref": "ew_c1", "cr": 1.0}], "spawnPoints": [[x - 14, y - 2, 90]]})
    steps.append(("range", label, (x, y, who, dx, dy)))
for (label, cr, bp, rec, mx, plan), (x, y) in zip(WAVES, WSPOTS):
    s = dict(BASE)
    s.update({"SpawnOption": 0, "Reset": 1, "ResetTime": 4, "Respawns": -1, "DifficultyIndex": 4, "RecCreatures": rec, "MaxCreatures": mx})
    encs.append({"from": "nw_goblingrp", "tag": f"EW_{label.upper()}", "x": x, "y": y, "w": 6, "h": 6, "set": s,
                 "creatures": [{"resref": bp, "cr": cr}], "spawnPoints": [[x + 12, y + 12, 90]]})
    steps.append(("wave", label, (x, y, plan)))

# No henchman spot may fall inside another encounter (a creature stepping into one becomes its last-entered creature).
for kind, label, args in steps:
    if kind == "range" and args[2]:
        hx, hy = args[0] + args[3], args[1] - 3 + args[4]
        for e in encs:
            assert not (abs(hx - e["x"]) <= 4 and abs(hy - e["y"]) <= 4), (label, e["tag"])

scene = {"tileset": "tde01", "tile": 4, "size": 26, "pc": [4, 4, 0], "facing": 90, "seconds": 0, "gui": True,
         "factions": "Prelude", "encounters": encs}
for name, spec in {"ew_c1": {"template": "nw_goblina", "hitPoints": 1, "challengeRating": 1.0},
                   "ew_c6": {"template": "nw_goblina", "hitPoints": 1, "challengeRating": 6.0},
                   "ew_g": {"template": "nw_goblina", "hitPoints": 1},
                   "ew_h12": {"template": "nw_bandit001", "hitPoints": 200, "classLevels": [{"class": 4, "level": 12}]}}.items():
    if name != "ew_h12":
        spec["scripts"] = {"ScriptSpawn": "ew_spawn"}
        spec["tag"] = "EW_" + name[3:].upper()
    with open(os.path.join(HERE, name + ".utc.json"), "w", encoding="utf-8", newline="") as f:
        f.write(json.dumps(spec) + "\n")

lines = ['#include "ew_inc"', "// Generated by parity/gen_encounterwaves.py.", "", "void main()", "{",
         "    object pc = GetEnteringObject();",
         '    if (!GetIsPC(pc) || GetLocalInt(GetModule(), "started")) return;',
         '    SetLocalInt(GetModule(), "started", 1);', "    SetPlotFlag(pc, TRUE);",
         '    Log("start|pchd=" + IntToString(GetHitDice(pc)) + "|xp=" + IntToString(GetXP(pc)));', "    float t = 4.0;"]
for kind, label, args in steps:
    if kind == "range":
        x, y, who, dx, dy = args
        lines.append(f'    Range("{label}", {x}.0, {y}.0, "{who}", {float(dx)}, {float(dy)}, t); t += 8.0;')
    else:
        x, y, plan = args
        lines.append(f'    Waves("{label}", {x}.0, {y}.0, {1 if plan == "npc" else 0}, t); t += 40.0;')
lines += ['    DelayCommand(t, Log("end"));', "    DelayCommand(t + 1.0, VDone());", "}"]
total = sum(8.0 if k == "range" else 40.0 for k, _, _ in steps) + 10
scene["seconds"] = int(total) + 90
with open(os.path.join(HERE, "scene.json"), "w", encoding="utf-8", newline="") as f:
    json.dump(scene, f, indent=1)
with open(os.path.join(HERE, "vis_main.nss"), "w", encoding="utf-8", newline="") as f:
    f.write("\n".join(lines) + "\n")
print(len(encs), "encounters, seconds", scene["seconds"])
