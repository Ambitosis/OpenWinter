# Generates parity/suites/hp_blueprints/parity_main.nss: hit points of base-game creature blueprints.
# The list comes from: openwinter-tools list "" utc --base > utc_base.txt
# Familiar and companion families (nw_ac_*, nw_fm_*, x0_fm_* ...) keep only levels 1, 10, 20 and 40.
import os, re, sys

names = sorted(set(open(sys.argv[1]).read().split()))
family = re.compile(r"^(nw_ac_|nw_fm_|x0_ac_|x0_fm_|x1_ac_|x1_fm_|x2_fm_)")
keep = []
for n in names:
    if family.match(n):
        m = re.search(r"(\d+)$", n)
        if not m or int(m.group(1)) not in (1, 10, 20, 40): continue
    keep.append(n)

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "suites", "hp_blueprints")
os.makedirs(root, exist_ok=True)
out = []
out.append("// Hit points of base-game creature blueprints as spawned: GetMaxHitPoints, GetCurrentHitPoints, Constitution\n")
out.append("// and hit dice, read 0.5 s after creation. Generated by parity/gen_hp_blueprints.py.\n")
out.append('#include "parity_inc"\n\n')
out.append("""void Read(object o, string r)
{
    PLog("hp." + r, IntToString(GetMaxHitPoints(o)) + "/" + IntToString(GetCurrentHitPoints(o))
        + " con=" + IntToString(GetAbilityScore(o, ABILITY_CONSTITUTION)) + " hd=" + IntToString(GetHitDice(o)));
    DestroyObject(o);
}

void B(string r, int i)
{
    object o = CreateObject(OBJECT_TYPE_CREATURE, r, PCentre(IntToFloat(i % 10) * 3.0 - 15.0, IntToFloat(i / 10) * 3.0 - 15.0));
    if (!GetIsObjectValid(o)) { PLog("hp." + r, "invalid"); return; }
    DelayCommand(0.5, Read(o, r));
}

""")
chunk = 40
batches = [keep[i:i + chunk] for i in range(0, len(keep), chunk)]
for bi, b in enumerate(batches):
    out.append("void Batch%d()\n{\n" % bi)
    for i, n in enumerate(b):
        out.append('    B("%s", %d);\n' % (n, i))
    out.append("}\n\n")
out.append("void main()\n{\n")
for bi in range(len(batches)):
    out.append("    DelayCommand(%.1f, Batch%d());\n" % (1.0 + bi * 1.0, bi))
out.append("    DelayCommand(%.1f, PDone());\n}\n" % (3.0 + len(batches) * 1.0))
open(os.path.join(root, "parity_main.nss"), "w", encoding="utf-8", newline="").write("".join(out))
print(len(keep), "blueprints,", len(batches), "batches")
