# Generates parity/suites/items_value*/parity_main.nss: the value of a longsword with one item property, for every
# itempropdef row across its subtypes and cost table values.
# Usage: gen_value.py <dir of base-game 2DA dumps>, each made with: openwinter-tools 2da <name> 2000 --base > <name>.txt
import sys, os

dumps = sys.argv[1]
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "suites")

def tda(name):
    p = os.path.join(dumps, name.lower() + ".txt")
    if not os.path.exists(p): return None
    lines = [l for l in open(p).read().split("\n") if l.strip()]
    cols = lines[0].split("\t")
    return [dict(zip(cols, l.split("\t"))) for l in lines[1:]]

def blank(v): return v is None or v == "****" or v == ""

ipd = tda("itempropdef")
costtables = tda("iprp_costtable")
params = tda("iprp_paramtable")

def rows_of(name):
    t = tda(name)
    return list(range(len(t))) if t else []

def sample(rows, n):
    if len(rows) <= n: return rows
    step = len(rows) / n
    return sorted(set(rows[int(i * step)] for i in range(n)) | {rows[-1]})

cases = []  # (type, sub, cost, param1)
for t, row in enumerate(ipd):
    if blank(row.get("Label")) or row["Label"] == "****": continue
    subs = rows_of(row["SubTypeResRef"]) if not blank(row["SubTypeResRef"]) else [-1]
    ct = row["CostTableResRef"]
    costs = [-1]
    if not blank(ct) and int(ct) > 0:
        costs = rows_of(costtables[int(ct)]["Name"]) or [-1]
    p1 = row.get("Param1ResRef")
    p1rows = [-1]
    if not blank(p1):
        p1rows = rows_of(params[int(p1)]["TableResRef"]) or [-1]
    subs = subs or [-1]
    s0 = subs[1] if len(subs) > 1 else subs[0]
    c0 = costs[1] if len(costs) > 1 else costs[0]
    p0 = p1rows[0]
    seen = set()
    for s in sample(subs, 24):
        seen.add((t, s, c0, p0))
    for c in sample(costs, 40):
        seen.add((t, s0, c, p0))
    for p in sample(p1rows, 6):
        seen.add((t, s0, c0, p))
    cases.extend(sorted(seen))

per_suite = 1400
parts = [cases[i:i + per_suite] for i in range(0, len(cases), per_suite)]
for n, group in enumerate(parts):
    suite = "items_value" + str(n + 1)
    os.makedirs(os.path.join(root, suite), exist_ok=True)
    out = ["// The value of a longsword with one item property (part %d of %d), by type, subtype, cost value and param1.\n" % (n + 1, len(parts)),
           "// Generated by parity/gen_value.py.\n",
           '#include "parity_items"\n\n',
           """void P(int nType, int nSub, int nCost, int nParam1)
{
    object o = CreateObject(OBJECT_TYPE_ITEM, "nw_wswls001", PCentre());
    itemproperty ip = ItemPropertyCustom(nType, nSub, nCost, nParam1);
    string k = "ip." + IntToString(nType) + "." + IntToString(nSub) + "." + IntToString(nCost) + "." + IntToString(nParam1) + ".";
    PLogI(k + "valid", GetIsItemPropertyValid(ip));
    AddItemProperty(DURATION_TYPE_PERMANENT, ip, o);
    PLog(k + "props", PIpList(o));
    PLogI(k + "gpv", GetGoldPieceValue(o));
    DestroyObject(o);
}

"""]
    chunks = [group[i:i + 50] for i in range(0, len(group), 50)]
    for i, c in enumerate(chunks):
        out.append("void C%d()\n{\n" % i)
        for (t, s, cv, p) in c:
            out.append("    P(%d, %d, %d, %d);\n" % (t, s, cv, p))
        if i == len(chunks) - 1: out.append("    PDone();\n")
        out.append("}\n\n")
    out.append("void main()\n{\n")
    for i in range(len(chunks)):
        out.append("    DelayCommand(%.1f, C%d());\n" % (2.0 + 0.2 * i, i))
    out.append("}\n")
    with open(os.path.join(root, suite, "parity_main.nss"), "w", newline="") as f:
        f.write("".join(out))
    print(suite, len(group))
